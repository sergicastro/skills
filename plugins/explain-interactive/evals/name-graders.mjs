// Writes each eval case's graders/name-*.md from the table below: one regex grader per project-specific
// name the case's prompt.md quotes. Edit the table, then run:  node plugins/explain-interactive/evals/name-graders.mjs
// test/eval-graders.test.mjs fails when the files on disk differ from what this would write.
import { readdirSync, writeFileSync, unlinkSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const r = String.raw;
// case -> [slug, key, used, flags]
//   key:  how the name may be written as a CAST/GLOSSARY key (a space matches any whitespace)
//   used: how a mention anywhere in the content file is spotted
//   flags: "i" ignores case; PATH and TZ keep case, since "path" is an ordinary word
export const NAMES = {
  "before-after": [
    ["notes-app", r`(?:acme/)?notes-app`, r`notes-app`, "i"],
    ["routes-notes-py", r`(?:routes/)?notes\.py`, r`notes\.py`, "i"],
    ["require-user", r`require_user`, r`require_user`, "i"],
    ["export-notes", r`export_notes`, r`export_notes`, "i"],
    ["share-note", r`share_note`, r`share_note`, "i"],
    ["note-history", r`note_history`, r`note_history`, "i"],
    ["auth-middleware", r`AuthMiddleware`, r`AuthMiddleware`, "i"],
    ["app-py", r`app\.py`, r`\bapp\.py`, "i"],
    ["request-state-user", r`request\.state(?:\.user)?`, r`request\.state\.user`, "i"],
    ["public-paths", r`PUBLIC_PATHS`, r`PUBLIC_PATHS`, "i"],
  ],
  "concept": [
    ["venv", r`\.?venv`, r`\.venv\b`, "i"],
    ["site-packages", r`site-packages`, r`site-packages`, "i"],
    ["bin-python", r`(?:\.venv/)?bin/python3?`, r`bin/python`, "i"],
    ["path-variable", r`\$?PATH`, r`\bPATH\b`, ""],
    ["pip", r`pip`, r`\bpip\b`, "i"],
    ["sys-prefix", r`sys\.prefix`, r`sys\.prefix`, "i"],
    ["requirements-txt", r`requirements\.txt`, r`requirements\.txt`, "i"],
  ],
  "debugging": [
    ["test-report-groups-by-day", r`test_report_groups_by_day`, r`test_report_groups_by_day`, "i"],
    ["acme-metrics", r`(?:acme/)?metrics`, r`acme/metrics`, "i"],
    ["events-table", r`events(?: table)?`, r`<code>events</code>|\bevents table`, "i"],
    ["datetime-now", r`datetime\.now`, r`datetime\.now`, "i"],
    ["created-at", r`(?:DATE\()?created_at\)?`, r`created_at`, "i"],
    ["tz", r`TZ(?:=UTC)?`, r`\bTZ\b`, ""],
  ],
  "decision": [
    ["recipe-site", r`(?:acme/)?recipe-site`, r`recipe-site`, "i"],
    ["jobs-table", r`jobs(?: table)?`, r`<code>jobs</code>|\bjobs table`, "i"],
    ["skip-locked", r`(?:SELECT\s+\S*\s*)?(?:FOR UPDATE )?SKIP LOCKED`, r`SKIP LOCKED`, "i"],
  ],
  "walkthrough-whatif": [
    ["shop-api", r`(?:acme/)?shop-api`, r`shop-api`, "i"],
    ["post-payments", r`(?:POST )?/payments`, r`/payments`, "i"],
    ["idempotency-key-header", r`Idempotency[-\s]Key`, r`Idempotency[-\s]Key(?!s)`, "i"],
    ["create-payment", r`create_payment`, r`create_payment`, "i"],
    ["idempotency-keys-table", r`idempotency_keys`, r`idempotency_keys`, "i"],
  ],
};

const QUOTE = "[\"'`]?";
// Passes when the name never appears, or appears as a key inside the CAST or GLOSSARY object: the scan
// stops at the first "}" (their values are plain strings, so that is the object's end), and a key must
// start an entry, so "Idempotency-Key:" inside a value doesn't count.
export function pattern(key, used) {
  const ws = s => s.replaceAll(" ", r`\s+`);
  return r`^(?![\s\S]*(?:` + ws(used) + "))"
    + r`|(?:CAST|GLOSSARY)\s*=\s*\{[^}]*?(?<=[{,\n][\t ]*)`
    + QUOTE + "(?:" + ws(key) + r`)(?:\(\))?` + QUOTE + r`\s*:`;
}

// The files a case should have: { "name-<slug>.md": text }
export function files(caseName) {
  const names = NAMES[caseName], weight = Math.round(1000 / names.length) / 1000;
  return Object.fromEntries(names.map(([slug, key, used, flags]) => [`name-${slug}.md`, [
    "---",
    `# generated by evals/name-graders.mjs: ${slug} has a CAST or GLOSSARY entry if the page uses it`,
    "type: regex",
    `pattern: '${pattern(key, used).replaceAll("'", "''")}'`,
    ...(flags ? [`flags: ${flags}`] : []),
    `weight: ${weight}`,
    "target:",
    "  source: file",
    "  path: out/page.content.js",
    "---",
    "",
  ].join("\n")]));
}

export const EVALS = dirname(fileURLToPath(import.meta.url));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const c of Object.keys(NAMES)) {
    const dir = join(EVALS, c, "graders"), want = files(c);
    for (const f of readdirSync(dir)) if (f.startsWith("name-") && !(f in want)) unlinkSync(join(dir, f));
    for (const [f, text] of Object.entries(want)) writeFileSync(join(dir, f), text);
  }
}
